import { createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { CommandLayout } from "@/components/eagle/command-layout";
import { Panel, PageHeader, TechLabel, SeverityTag } from "@/components/eagle/hud";
import { EgyptMap } from "@/components/eagle/egypt-map";
import { useSim } from "@/lib/sim-context";
import { cn } from "@/lib/utils";
import { toast } from "sonner";

export const Route = createFileRoute("/incidents")({
  head: () => ({
    meta: [
      { title: "Incident Center — EAGLE EYE" },
      {
        name: "description",
        content: "Simulated incident management: severity triage, timelines, map correlation and response assignment.",
      },
      { property: "og:title", content: "Incident Center — EAGLE EYE" },
      { property: "og:description", content: "Track, analyse and resolve simulated incidents across monitored zones." },
    ],
  }),
  component: IncidentsPage,
});

function IncidentsPage() {
  const { incidents, layers, selectedIncident, selectIncident } = useSim();
  const [filter, setFilter] = useState<"ALL" | "ACTIVE" | "MONITORING" | "RESOLVED">("ALL");
  const list = incidents.filter((i) => filter === "ALL" || i.status === filter);
  const sel = incidents.find((i) => i.id === selectedIncident) ?? list[0] ?? null;

  return (
    <CommandLayout>
      <div className="space-y-5 p-4 md:p-6">
        <PageHeader
          eyebrow="MODULE 07 — RESPONSE MANAGEMENT"
          title="INCIDENT CENTER"
          description="All incidents are simulated events generated by the EAGLE EYE scenario engine."
          action={
            <div className="panel flex overflow-hidden">
              {(["ALL", "ACTIVE", "MONITORING", "RESOLVED"] as const).map((f) => (
                <button
                  key={f}
                  onClick={() => setFilter(f)}
                  className={cn(
                    "label-tech px-3 py-2.5",
                    filter === f ? "bg-gold/15 text-gold" : "text-muted-foreground hover:text-foreground",
                  )}
                >
                  {f}
                </button>
              ))}
            </div>
          }
        />

        <div className="grid gap-4 xl:grid-cols-[380px_1fr]">
          <div className="space-y-3">
            {list.map((i) => (
              <button
                key={i.id}
                onClick={() => selectIncident(i.id)}
                className={cn(
                  "panel corner-ticks block w-full p-4 text-left transition-colors",
                  sel?.id === i.id && "border-gold/50",
                )}
              >
                <div className="flex items-center justify-between">
                  <span className="font-mono text-xs text-gold">INCIDENT #{i.id}</span>
                  <SeverityTag level={i.severity} />
                </div>
                <p className="mt-2 text-sm font-semibold">{i.title}</p>
                <dl className="mt-3 grid grid-cols-2 gap-2 font-mono text-[10px] text-muted-foreground">
                  <span>TYPE — {i.type}</span>
                  <span>DETECTED — {i.detected}</span>
                  <span className="col-span-2">LOCATION — {i.location}</span>
                </dl>
                <span
                  className={cn(
                    "label-tech mt-3 inline-block rounded-sm border px-2 py-1",
                    i.status === "ACTIVE"
                      ? "border-critical/40 text-critical"
                      : i.status === "MONITORING"
                        ? "border-gold/40 text-gold"
                        : "border-signal/40 text-signal",
                  )}
                >
                  {i.status}
                </span>
              </button>
            ))}
          </div>

          <div className="space-y-4">
            <Panel title="MAP CORRELATION" bodyClassName="p-0">
              <EgyptMap
                layers={layers}
                incidents={incidents}
                selectedId={sel?.id ?? null}
                activeZone={sel?.zone ?? null}
                onSelectIncident={selectIncident}
                className="h-[42vh] w-full"
                compact
              />
            </Panel>

            {sel && (
              <Panel title={`INCIDENT #${sel.id} — DETAIL`} bodyClassName="p-5 space-y-5">
                <p className="max-w-3xl text-sm leading-relaxed text-foreground/85">{sel.summary}</p>
                <div className="flex flex-wrap gap-2">
                  {["VIEW ON MAP", "ANALYZE", "ASSIGN RESPONSE", "CLOSE INCIDENT"].map((a) => (
                    <button
                      key={a}
                      onClick={() => toast.success(`${a} — simulated action executed`, { description: `Incident ${sel.id}` })}
                      className="label-tech rounded-sm border border-border/60 px-3 py-2.5 text-foreground/80 transition-colors hover:border-gold/50 hover:text-gold"
                    >
                      {a}
                    </button>
                  ))}
                </div>
                <div>
                  <TechLabel className="text-gold/80">INCIDENT TIMELINE</TechLabel>
                  <ol className="mt-3 space-y-3 border-l border-border/60 pl-5">
                    {sel.timeline.map((t) => (
                      <li key={t.t} className="relative">
                        <span className="absolute -left-[26px] top-1.5 h-2 w-2 rounded-full bg-gold" />
                        <span className="font-mono text-xs text-gold">{t.t}</span>
                        <p className="text-[12px] text-foreground/85">{t.label}</p>
                      </li>
                    ))}
                  </ol>
                </div>
              </Panel>
            )}
          </div>
        </div>
      </div>
    </CommandLayout>
  );
}
